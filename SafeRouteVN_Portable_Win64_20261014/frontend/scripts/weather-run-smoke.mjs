import puppeteer from 'puppeteer-core';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const origin=process.argv[2] || 'http://127.0.0.1:5178';
const output=resolve(process.argv[3] || '../outputs/weather-ui');
await mkdir(output,{recursive:true});
const browser=await puppeteer.launch({headless:true,pipe:true,executablePath:process.env.SAFEROUTE_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const report={status:'RUNNING',errors:[],steps:[]};
const save=()=>writeFile(resolve(output,'result.json'),JSON.stringify(report,null,2));
try {
  const page=await browser.newPage();await page.setViewport({width:1600,height:1200});page.setDefaultTimeout(300000);
  page.on('pageerror',e=>report.errors.push(e.message));
  await page.setRequestInterception(true);
  page.on('request',r=>new URL(r.url()).hostname==='127.0.0.1' || r.url().startsWith('data:') ? r.continue():r.abort());
  await page.goto(origin+'/admin',{waitUntil:'domcontentloaded'});
  await page.waitForSelector('.weather-run-panel');
  await page.evaluate(()=>document.querySelectorAll('details').forEach(e=>e.open=true));
  const click=async label=>{
    await page.waitForFunction(text=>[...document.querySelectorAll('button')].some(b=>b.textContent.trim()===text && !b.disabled),{},label);
    await page.evaluate(text=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text && !b.disabled).click(),label);
  };
  await click('Fetch weather & prepare session');
  await page.waitForFunction(()=>document.querySelector('.weather-run-panel')?.innerText.includes('Open new session'));
  const intent=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('saferoute.weather-run.intent.v1')));
  report.run_id=intent.runId;report.steps.push('fresh_weather_ready');await save();console.log('weather READY');
  await click('Open new session');
  await page.waitForFunction(()=>document.querySelector('.weather-run-panel')?.innerText.includes('Đang chạy S2'));
  const sid=await page.$eval('.admin-page',e=>e.dataset.sessionId);report.session_id=sid;
  const api=async path=>page.evaluate(async path=>{const r=await fetch(path,{headers:{'X-SafeRoute-Local':'1'}});const v=await r.json();if(!r.ok)throw new Error(JSON.stringify(v));return v.data;},path);
  const beforeOptimize=await api(`/api/sessions/${sid}/state`);report.initial_time=beforeOptimize.current_time;
  if(beforeOptimize.current_time.startsWith('2026-09-27'))throw new Error('Historical epoch leaked into new session');
  await page.waitForFunction(()=>!document.querySelector('.cta-optimize')?.disabled);
  await page.click('.cta-optimize');
  await page.waitForFunction(()=>[...document.querySelectorAll('.alt-view-btn')].filter(b=>!b.disabled).length===3);
  await page.click('[aria-label="Select BALANCED"]');
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent.includes('Accept')&&!b.disabled));
  await page.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Accept')&&!b.disabled).click());
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent.trim()==='Tới mốc sự kiện'&&!b.disabled));
  await click('Tới mốc sự kiện');
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent.trim()==='Kích hoạt + replan'&&!b.disabled));
  const before=await api(`/api/sessions/${sid}/state`);
  await click('Kích hoạt + replan');
  await page.waitForFunction(()=>[...document.querySelectorAll('.alt-view-btn')].filter(b=>!b.disabled).length===3);
  const after=await api(`/api/sessions/${sid}/state`);
  if(after.order_ids.length!==before.order_ids.length+1 || JSON.stringify(after.vehicles)!==JSON.stringify(before.vehicles) || JSON.stringify(after.delivered_prefix)!==JSON.stringify(before.delivered_prefix))throw new Error('Event custody/prefix invariant failed');
  report.steps.push('three_profiles','accept','observed_event_barrier','urgent_event','three_replan_profiles','custody_unchanged');
  report.custody=after.vehicles.map(v=>({vehicle_id:v.vehicle_id,onboard_order_ids:v.onboard_order_ids,active_commitment:v.active_commitment}));
  await page.click('[aria-label="Select BALANCED"]');
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent.includes('Accept')&&!b.disabled));
  await page.evaluate(()=>[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Accept')&&!b.disabled).click());
  await page.waitForFunction(()=>document.querySelector('.cta-optimize')&&!document.querySelector('.cta-optimize').disabled);
  const accepted=await api(`/api/sessions/${sid}/state`);
  if(!accepted.accepted_trajectory)throw new Error('Replan was not accepted');
  report.steps.push('accept_replan');await save();
  await page.screenshot({path:resolve(output,'weather-run.png'),fullPage:true});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForSelector('.weather-run-panel');
  await page.waitForFunction(id=>document.querySelector('.admin-page')?.dataset.sessionId===id,{},sid);
  report.steps.push('reload_keeps_run');
  if(report.errors.length)throw new Error(report.errors.join('; '));
  report.status='PASS';console.log('WEATHER_UI_PASS');
}catch(e){report.status='FAIL';report.failure=String(e);throw e;}
finally{await save();await browser.close();}
